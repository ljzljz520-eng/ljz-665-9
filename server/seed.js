async function main() {
  await db.init();
  const force = process.argv.includes('--force');
  const existing = await db.count();
  if (existing > 0 && !force) {
    console.log(`数据库中已有 ${existing} 条设备数据，跳过灌入。如需清空重建：npm run seed -- --force`);
    await db.close();
    return;
  }
  if (force) {
    // 通过逐个删除清空（会连带处理附件/日志）
    const { list } = await db.listEquipment({ page: 1, pageSize: 100000 });
    for (const e of list) {
      await db.addLog({ equipmentId: e.id, action: '删除', detail: '种子数据重建：清空旧数据', operator: 'system' });
      await db.deleteEquipment(e.id);
    }
  }
  for (const d of rows) {
    const e = await db.createEquipment(d);
    await db.addLog({
      equipmentId: e.id,
      action: '新建',
      detail: `种子数据导入：${d.stationName} / ${d.equipmentCode}`,
      operator: 'system'
    });
  }
  console.log(`已灌入 ${rows.length} 条设备档案（驱动：${config.dbDriver}）`);
  await db.close();
}

main().catch((err) => {
  console.error('种子数据执行失败：', err.message);
  process.exit(1);
});
